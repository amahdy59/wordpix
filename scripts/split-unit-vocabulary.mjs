#!/usr/bin/env node
/**
 * Moves every unit's vocabulary out of `lessons.ts` and into its own module.
 *
 *   node scripts/split-unit-vocabulary.mjs [--dry-run]
 *
 * `lessons.ts` was 3.39 MB and it *was* the main bundle: 3.34 MB minified,
 * 587 KB gzipped, downloaded and parsed in full by someone who opened one
 * unit. 79.6% of those bytes are the 182 `*_VOCABULARY` arrays, so moving
 * those behind dynamic imports is most of the file.
 *
 * The groups stay where they are. They are 17.6% of the file, and
 * `resolveGroup`, `nextGroupToStudy` and `getNextGroupChronological` all read
 * them synchronously from anywhere in the app — making those async would push
 * a promise through the router and the reducer for a sixth of the payload.
 * Vocabulary is the part that is both huge and genuinely unit-scoped.
 *
 * `bedroom` is deliberately left eager. It is `DEFAULT_UNIT_ID`, the placement
 * quiz draws on it before any unit has been chosen, and it is what the splash
 * screen shows — so it would be fetched on nearly every cold load anyway, and
 * a second round trip to get it would be a regression dressed as a saving.
 *
 * Idempotent: it detects an already-split file and stops.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DATA = join(ROOT, "src", "app", "data");
const LESSONS = join(DATA, "lessons.ts");
const UNITS_DIR = join(DATA, "units");

const DRY_RUN = process.argv.includes("--dry-run");

/** The unit kept in the main bundle; see the note above. */
const EAGER_UNIT = "bedroom";

/**
 * 10,406 of the 10,848 vocabulary items carry this exact string. Written out
 * each time it costs about 730 KB of source — more than the entire groups
 * section — for one sentence. Gzip hides it on the wire; the parser does not.
 */
const PLACEHOLDER_DESCRIPTION = "A visual representation of this specific concept.";

const source = await readFile(LESSONS, "utf8");

if (source.includes("./units/")) {
  console.log("lessons.ts already imports from ./units — nothing to split.");
  process.exit(0);
}

const lines = source.split("\n");

/** Extracts `export const NAME... = [` through its closing `];`, inclusive. */
function extractBlock(startPattern) {
  const start = lines.findIndex((l) => startPattern.test(l));
  if (start === -1) return null;
  let end = start;
  while (end < lines.length && lines[end] !== "];") end += 1;
  return { start, end, text: lines.slice(start, end + 1).join("\n") };
}

// Map each unit id to the CONST prefix its arrays use, read from COURSE_UNITS
// rather than guessed from the id — "living-room" is LIVING_ROOM but
// "3d-printer-lab" is _3D_PRINTER_LAB, and only the file knows which.
const unitEntries = [
  ...source.matchAll(
    /\n {2}"?([a-z0-9-]+)"?: \{\n {4}id: "([a-z0-9-]+)",[\s\S]*?vocabulary: (\w+)_VOCABULARY,\n {2}\},/g
  ),
].map(([, key, id, prefix]) => ({ key, id, prefix }));

if (!unitEntries.length) {
  console.error("Could not read any unit entries from COURSE_UNITS — aborting.");
  process.exit(1);
}

console.log(`Splitting vocabulary for ${unitEntries.length} units`);

if (!DRY_RUN) await mkdir(UNITS_DIR, { recursive: true });

let movedBytes = 0;
let dedupedBytes = 0;
const removals = [];
const wordIdsByUnit = new Map();

for (const { id, prefix } of unitEntries) {
  const block = extractBlock(new RegExp(`^export const ${prefix}_VOCABULARY: VocabularyItem\\[\\] = \\[$`));
  if (!block) {
    console.error(`  ! no ${prefix}_VOCABULARY block found`);
    process.exit(1);
  }

  const ids = [...block.text.matchAll(/\n {4}id: "([^"]+)",/g)].map((m) => m[1]);
  wordIdsByUnit.set(id, ids);

  const body = block.text
    .replace(`export const ${prefix}_VOCABULARY: VocabularyItem[] = [`, "export const VOCABULARY: VocabularyItem[] = [")
    .replaceAll(`description: "${PLACEHOLDER_DESCRIPTION}",`, "description: PLACEHOLDER_DESCRIPTION,");

  const deduped = (block.text.match(new RegExp(PLACEHOLDER_DESCRIPTION, "g")) ?? []).length;
  dedupedBytes += deduped * PLACEHOLDER_DESCRIPTION.length;
  movedBytes += block.text.length;

  // A unit whose descriptions are all hand-written does not import the shared
  // placeholder; an unused import is a lint error, not a harmless extra line.
  const usesPlaceholder = body.includes("description: PLACEHOLDER_DESCRIPTION");
  const file = `// GENERATED by scripts/split-unit-vocabulary.mjs — do not hand-edit.
//
// One unit's vocabulary, in its own chunk so that opening a different unit
// never downloads it. Loaded through data/vocabulary.ts, not imported directly
// by screens.
import type { VocabularyItem } from "../lessons";
${usesPlaceholder ? 'import { PLACEHOLDER_DESCRIPTION } from "../placeholderDescription";\n' : ""}
${body}
`;

  if (!DRY_RUN) await writeFile(join(UNITS_DIR, `${id}.ts`), file);
  removals.push(block);
}

// ---- rewrite lessons.ts ----------------------------------------------------

// Drop the extracted blocks back-to-front so earlier indices stay valid.
let rewritten = lines.slice();
for (const block of removals.sort((a, b) => b.start - a.start)) {
  rewritten.splice(block.start, block.end - block.start + 2); // + the blank line after
}
let out = rewritten.join("\n");

// `vocabulary: X_VOCABULARY` becomes the id list the catalog can answer from.
for (const { id, prefix } of unitEntries) {
  const ids = wordIdsByUnit.get(id);
  out = out.replace(
    `    vocabulary: ${prefix}_VOCABULARY,\n`,
    `    wordIds: ${JSON.stringify(ids)},\n`
  );
}

// The one unit that stays in the main bundle keeps its historic export name,
// which is also what the test suite imports.
out = out.replace(
  'const LOCAL_SCENE_IMAGES = "./scene-images";',
  `const LOCAL_SCENE_IMAGES = "./scene-images";

export { VOCABULARY as ${EAGER_UNIT.toUpperCase()}_VOCABULARY } from "./units/${EAGER_UNIT}";`
);

if (!DRY_RUN) {
  await writeFile(LESSONS, out);
  await writeFile(
    join(DATA, "placeholderDescription.ts"),
    `/**
 * The description carried by 10,406 of the 10,848 vocabulary items.
 *
 * Written out at each site it cost about 730 KB of source — more than the
 * whole groups section — to say one sentence 10,406 times. Shared here so a
 * unit chunk pays for it once.
 */
export const PLACEHOLDER_DESCRIPTION = "${PLACEHOLDER_DESCRIPTION}";
`
  );
}

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
console.log(`  vocabulary moved out   ${kb(movedBytes)}`);
console.log(`  placeholder deduped    ${kb(dedupedBytes)}`);
console.log(`  lessons.ts             ${kb(source.length)} → ${kb(out.length)}`);
if (DRY_RUN) console.log("\nDry run — nothing written.");
