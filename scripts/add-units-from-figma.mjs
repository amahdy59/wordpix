#!/usr/bin/env node
/**
 * Adds units the design file has and the app does not.
 *
 *   node scripts/add-units-from-figma.mjs <dump-id>... [--module N] [--dry-run]
 *
 * The sync has always reported these and refused to act on them, which was the
 * right default: committing artwork for a unit the course does not teach fills
 * directories `lessons.ts` never reads. Actually adding them is a curriculum
 * change, so it is a separate, deliberate step — this script.
 *
 * A dump id is not an app id. Figma prefixes some frames with their level
 * ("l5-hospital"), and the app has never carried that prefix, so it is
 * stripped. `human-body-head-and-face` has no prefix and keeps its name.
 *
 * What it writes, per unit:
 *   src/app/data/units/<id>.ts   the vocabulary, as its own lazily-loaded chunk
 *   lessons.ts                   groups, topics, and the COURSE_UNITS entry
 *   data/vocabulary.ts           the loader entry
 *   lessons.ts COURSE_MODULES    membership, so Explore can actually reach it
 *
 * The last of those is easy to forget and silent when missed: the unit exists,
 * routes resolve, and it appears nowhere in the UI.
 */

import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DATA = join(ROOT, "src", "app", "data");
const LESSONS = join(DATA, "lessons.ts");
const VOCAB = join(DATA, "vocabulary.ts");
const DUMP = join(ROOT, "figma-dump");

const args = process.argv.slice(2);
const DRY_RUN = args.includes("--dry-run");
const moduleAt = args.indexOf("--module");
const FORCE_MODULE = moduleAt === -1 ? null : args[moduleAt + 1];
const dumpIds = args.filter((a, i) => !a.startsWith("--") && args[i - 1] !== "--module");

if (!dumpIds.length) {
  console.error("Name at least one figma-dump id.");
  process.exit(1);
}

/**
 * Every group carries `story` copy for the story drill, in the same template
 * the existing 182 units use. Omitting it does not fail a type check — the
 * field is optional — it just makes that one exercise silently unavailable
 * for the new units.
 */

/** Words per lesson group, matching every existing unit: ceil(words / 15). */
const GROUP_SIZE = 15;

/** "l5-hospital" → "hospital"; anything else is already the app's own id. */
const appIdOf = (dumpId) => dumpId.replace(/^l\d+-/, "");

/** "l5-hospital" → 5, for placing the unit in the right course module. */
const levelOf = (dumpId) => {
  const m = dumpId.match(/^l(\d+)-/);
  return m ? Number(m[1]) : null;
};

const CONST = (id) => {
  const upper = id.toUpperCase().replace(/-/g, "_");
  return /^\d/.test(upper) ? `_${upper}` : upper;
};

const titleCase = (id) =>
  id
    .split("-")
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(" ");

let lessons = await readFile(LESSONS, "utf8");
let vocab = await readFile(VOCAB, "utf8");

const added = [];
const warnings = [];

for (const dumpId of dumpIds) {
  const path = join(DUMP, `${dumpId}.json`);
  if (!existsSync(path)) {
    console.error(`  ! no dump for ${dumpId}`);
    process.exit(1);
  }
  const dump = JSON.parse(await readFile(path, "utf8"));
  const id = appIdOf(dumpId);

  if (lessons.includes(`\n  ${JSON.stringify(id)}: {\n`) || lessons.includes(`\n  ${id}: {\n`)) {
    warnings.push(`${id} already exists in COURSE_UNITS — skipped`);
    continue;
  }

  // Figma occasionally repeats a card inside one frame; "crown" appears twice
  // in Head & Face. Within a unit an id must be unique, so the repeat goes.
  // Across units it may repeat freely — 1,841 ids already do — because word
  // lookup is unit-scoped.
  const seen = new Set();
  const cards = [];
  for (const card of dump.cards) {
    if (seen.has(card.id)) {
      warnings.push(`${id}: dropped repeated card "${card.id}"`);
      continue;
    }
    seen.add(card.id);
    cards.push(card);
  }

  const name = dump.name ?? `The ${titleCase(id)}`;
  const subject = name.replace(/^The /, "").toLowerCase();

  // --- the vocabulary module ------------------------------------------------

  const items = cards
    .map(
      (c) => `  {
    id: ${JSON.stringify(c.id)},
    label: ${JSON.stringify(c.label)},
    phonetic: ${JSON.stringify(c.ipa ?? "")},
    cefr: ${JSON.stringify(c.cefr ?? "A2")},
    img: ${JSON.stringify(`/word-images/${id}/${c.id}.avif`)},
    description: PLACEHOLDER_DESCRIPTION,
    topic: ${JSON.stringify(id)},
  },`
    )
    .join("\n");

  const unitModule = `// GENERATED by scripts/add-units-from-figma.mjs from figma-dump/${dumpId}.json.
//
// One unit's vocabulary, in its own chunk so that opening a different unit
// never downloads it. Loaded through data/vocabulary.ts, not imported directly
// by screens.
import type { VocabularyItem } from "../lessons";
import { PLACEHOLDER_DESCRIPTION } from "../placeholderDescription";

export const VOCABULARY: VocabularyItem[] = [
${items}
];
`;
  if (!DRY_RUN) await writeFile(join(DATA, "units", `${id}.ts`), unitModule);

  // --- groups and topics ----------------------------------------------------

  const groups = [];
  for (let i = 0; i < cards.length; i += GROUP_SIZE) {
    const slice = cards.slice(i, i + GROUP_SIZE);
    const n = groups.length + 1;
    const labels = slice.map((c) => c.label).join(", ");
    groups.push(`  {
    id: ${JSON.stringify(`${id}-${n}`)},
    name: ${JSON.stringify(`${name} ${n}`)},
    description: ${JSON.stringify(labels.length > 100 ? `Learn about ${labels.slice(0, 100)}...` : `Learn about ${labels}.`)},
    topicId: ${JSON.stringify(`${id}-${n}`)},
    wordIds: ${JSON.stringify(slice.map((c) => c.id))},
    story: ${JSON.stringify(`In this section, you will learn about ${labels}. These are essential items to know.`)},
  },`);
  }

  const c = CONST(id);
  const block = `export const ${c}_GROUPS: Lesson[] = [
${groups.join("\n")}
];

export const ${c}_TOPICS = ${c}_GROUPS.map((g) => ({
  id: g.id,
  name: g.name,
  itemsCount: g.wordIds.length,
}));

`;
  lessons = lessons.replace("export const COURSE_UNITS", block + "export const COURSE_UNITS");

  // --- the COURSE_UNITS entry ----------------------------------------------

  const key = /^[a-z][a-z0-9]*$/.test(id) ? id : JSON.stringify(id);
  const entry = `  ${key}: {
    id: ${JSON.stringify(id)},
    name: ${JSON.stringify(name)},
    description:
      ${JSON.stringify(`Explore real-life ${subject} vocabulary through 2D scene discovery, audio practice, recall matching, and sentence building.`)},
    heroImage: \`\${LOCAL_SCENE_IMAGES}/${id}-hero.avif\`,
    topics: ${c}_TOPICS,
    groups: ${c}_GROUPS,
    wordIds: ${JSON.stringify(cards.map((x) => x.id))},
  },
`;
  // Appended rather than sorted in: COURSE_UNITS order is curriculum order,
  // and ALL_GROUPS is derived from it, so inserting mid-list would renumber
  // what "the next lesson" means for existing learners.
  const closeAt = lessons.indexOf("\n};", lessons.indexOf("export const COURSE_UNITS"));
  lessons = lessons.slice(0, closeAt + 1) + entry + lessons.slice(closeAt + 1);

  // --- the loader -----------------------------------------------------------

  const loader = `  ${key}: () => import("./units/${id}").then((m) => m.VOCABULARY),\n`;
  const loadersEnd = vocab.indexOf("\n};", vocab.indexOf("const LOADERS"));
  vocab = vocab.slice(0, loadersEnd + 1) + loader + vocab.slice(loadersEnd + 1);

  // --- module membership ----------------------------------------------------

  const level = FORCE_MODULE ?? levelOf(dumpId);
  // The app has five modules; Figma marks some of these units level 6 and 7.
  // Until modules 6 and 7 exist, they join the most advanced one rather than
  // being invented a new taxonomy by a script.
  const moduleId = level === null ? null : `module-${Math.min(Number(level), 5)}`;
  if (moduleId) {
    if (Number(level) > 5) {
      warnings.push(`${id}: Figma marks it level ${level}; placed in ${moduleId}`);
    }
    const at = lessons.indexOf(`id: "${moduleId}"`);
    const listAt = lessons.indexOf("unitIds: [", at);
    const insertAt = lessons.indexOf("\n    ]", listAt);
    lessons = lessons.slice(0, insertAt) + `\n      ${JSON.stringify(id)},` + lessons.slice(insertAt);
  } else {
    warnings.push(`${id}: no level in the dump id — not added to any module`);
  }

  added.push({ id, name, words: cards.length, groups: groups.length, moduleId });
}

if (!DRY_RUN) {
  await writeFile(LESSONS, lessons);
  await writeFile(VOCAB, vocab);
}

console.log(`${DRY_RUN ? "Would add" : "Added"} ${added.length} unit(s):`);
for (const u of added) {
  console.log(`  ${u.id.padEnd(28)} ${String(u.words).padStart(3)} words, ${u.groups} groups → ${u.moduleId ?? "no module"}`);
}
if (warnings.length) {
  console.log("\nNotes:");
  for (const w of warnings) console.log(`  ${w}`);
}
if (DRY_RUN) console.log("\nDry run — nothing written.");
